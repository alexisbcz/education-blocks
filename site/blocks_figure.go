package site

import (
	h "github.com/alexisbcz/libhtml"
)

// ---------------------------------------------------------------- 15

func anatomyBlock() Block {
	return Block{
		Slug:        "anatomy",
		Title:       "Mechanism figure",
		Description: "y = Ax as a machine you could build: racks set x, gear ratios are the entries of A, and each row's feed bars add up to a y. Built with the anatomy skill; drag it, use the arrow keys, or let the tour run.",
		Tags:        []string{"isometric SVG", "anatomy", "live readout"},
		Wide:        true,
		Render:      anatomyFigure,
	}
}

// The fragment is generated by figures/matvec/build.mjs (node) from our own
// sources at build time, never from user input, so it is embedded as is.
func anatomyFigure() h.Node {
	b, err := static.ReadFile("static/anatomy/matvec.html")
	if err != nil {
		return h.P(h.Class("text-sm text-muted-foreground"), "Run node figures/matvec/build.mjs to build the figure.")
	}
	return h.Div(h.Class("mx-auto w-full max-w-3xl"), h.UnsafeHTML(string(b)))
}
