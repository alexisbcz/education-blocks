// BuildingBlocks lists the building physics gallery in display order. The
// numbers come from the standard design methods (ISO 6946, ISO 13788,
// ISO 7730, the BRE daylight formula, Sharp's double-wall model); each block
// names its simplifications in the small print.
func BuildingBlocks() []Block {
	return []Block{
		bldgHotBoxBlock(),
		bldgWallBlock(),
		bldgGlaserBlock(),
		bldgHeatLossBlock(),
		bldgMassBlock(),
		bldgSunBlock(),
		bldgDaylightBlock(),
		bldgCO2Block(),
		bldgComfortBlock(),
		bldgSoundBlock(),
	}
}

// bldgNote is the small print under a block's controls.
func bldgNote(s string) h.Node {
	return h.P(h.Class("text-xs leading-relaxed text-muted-foreground"), s)
}

func bldgSVG(attr, viewBox, label string) h.Node {
	return h.Svg(h.Data(attr, ""), h.ViewBox(viewBox), h.Class("block w-full select-none"), h.Role("img"), h.Aria("label", label))
}

func bldgButton(action, label string, icon h.Node) h.Node {
	return button.Button(button.VariantOutline, button.SizeSm, h.Type("button"), h.Data("action", action), icon, label)
}

