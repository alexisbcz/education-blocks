// plateSVG draws one boundary type as a cross-section (or a map view for
// a transform). Each feature is a focusable group with data-feature.
func plateSVG(kind string) h.Node {
	part := func(key string, children ...any) h.Node {
		name := key
		for _, f := range plateFeatures[kind] {
			if f.key == key {
				name = f.name
			}
		}
		return h.El("g", append([]any{h.Data("feature", key), h.TabIndex(0), h.Role("button"), h.Aria("label", name),
			h.Class("cursor-pointer outline-none [&_*]:transition-[stroke,fill,opacity] [&_*]:duration-150")}, children...)...)
	}
	p := func(d, cls string, extra ...any) h.Node {
		return h.El("path", append([]any{h.Attr("d", d), h.Class(cls)}, extra...)...)
	}
	stroke := "stroke-[var(--part)] [stroke-width:1.5]"
	// Literal class names: the stylesheet generator scans the Go source.
	fills := map[int]string{
		8:  "fill-[color-mix(in_oklab,var(--part)_16%,var(--code-bg))]",
		12: "fill-[color-mix(in_oklab,var(--part)_24%,var(--code-bg))]",
		16: "fill-[color-mix(in_oklab,var(--part)_32%,var(--code-bg))]",
		28: "fill-[color-mix(in_oklab,var(--part)_56%,var(--code-bg))]",
		30: "fill-[color-mix(in_oklab,var(--part)_60%,var(--code-bg))]",
	}
	fill := func(mix int) string { return fills[mix] + " " + stroke }
	arrow := func(x1, y1, x2, y2 float64) h.Node {
		dx, dy := x2-x1, y2-y1
		l := dx*dx + dy*dy
		if l == 0 {
			return nil
		}
		return h.Group(
			h.El("line", h.Attr("x1", fmt.Sprint(x1)), h.Attr("y1", fmt.Sprint(y1)), h.Attr("x2", fmt.Sprint(x2)), h.Attr("y2", fmt.Sprint(y2)),
				h.Class("stroke-foreground/60"), h.Attr("stroke-width", "1.5"), h.Attr("marker-end", "url(#plate-arrow-"+kind+")")),
		)
	}
	defs := h.El("defs", h.El("marker", h.ID("plate-arrow-"+kind), h.Attr("viewBox", "0 0 10 10"), h.Attr("refX", "8"), h.Attr("refY", "5"),
		h.Attr("markerWidth", "6"), h.Attr("markerHeight", "6"), h.Attr("orient", "auto-start-reverse"),
		h.El("path", h.Attr("d", "M0 0 L10 5 L0 10 z"), h.Class("fill-foreground/60"))))
	svg := func(children ...any) h.Node {
		return h.Svg(append([]any{h.ViewBox("0 0 560 260"), h.Class("block w-full [--part:color-mix(in_oklab,var(--foreground)_55%,var(--code-bg))] [&_[data-feature]:is(:hover,:focus-visible,[data-on])]:[--part:var(--brand)]"),
			h.Role("group"), h.Aria("label", "Cross-section of a "+kind+" plate boundary"), defs}, children...)...)
	}
	switch kind {
	case "divergent":
		return svg(
			// sea level
			h.El("line", h.Attr("x1", "0"), h.Attr("x2", "560"), h.Attr("y1", "40"), h.Attr("y2", "40"), h.Class("stroke-[var(--vec-u)]"), h.Attr("stroke-dasharray", "4 4"), h.Attr("stroke-opacity", "0.6")),
			part("asthenosphere", p("M0 150 L560 150 L560 250 L0 250 Z", fill(8))),
			part("magma", p("M250 250 C258 200 270 160 280 110 C290 160 302 200 310 250 Z", fill(30))),
			part("crust",
				p("M0 120 L180 108 L240 80 L262 72 L262 128 L180 140 L0 150 Z", fill(16)),
				p("M560 120 L380 108 L320 80 L298 72 L298 128 L380 140 L560 150 Z", fill(16))),
			part("ridge", p("M180 108 L240 80 L262 72 M298 72 L320 80 L380 108", "fill-none "+stroke+" [stroke-width:3]")),
			part("rift", p("M262 72 L270 96 L290 96 L298 72", "fill-none "+stroke+" [stroke-width:2.5]")),
			arrow(200, 190, 120, 190), arrow(360, 190, 440, 190),
			h.El("text", h.Attr("x", "8"), h.Attr("y", "34"), h.Class("fill-muted-foreground font-mono text-[10px]"), "sea level"),
		)
	case "convergent":
		return svg(
			h.El("line", h.Attr("x1", "0"), h.Attr("x2", "330"), h.Attr("y1", "60"), h.Attr("y2", "60"), h.Class("stroke-[var(--vec-u)]"), h.Attr("stroke-dasharray", "4 4"), h.Attr("stroke-opacity", "0.6")),
			part("slab", p("M0 70 L200 72 C240 74 270 100 300 150 L360 250 L310 250 L262 160 C240 120 222 102 200 100 L0 98 Z", fill(16))),
			part("trench", p("M188 72 C205 74 214 90 222 104", "fill-none "+stroke+" [stroke-width:3]")),
			part("continent", p("M250 70 L330 52 L380 44 L560 50 L560 140 L380 150 C330 150 300 120 270 100 Z", fill(12))),
			part("melt", p("M330 180 C340 150 350 120 362 70 C366 110 372 150 374 180 Z", fill(28))),
			part("arc", p("M342 52 L362 22 L382 46 Z", fill(30)), p("M362 22 L362 8", "fill-none "+stroke)),
			arrow(60, 85, 150, 85), arrow(500, 95, 420, 95),
		)
	default: // transform: map view
		return svg(
			part("offset",
				p("M60 30 L60 120", "fill-none "+stroke+" [stroke-width:4]"),
				p("M260 140 L260 230", "fill-none "+stroke+" [stroke-width:4]")),
			part("fault", p("M60 125 L260 135", "fill-none "+stroke+" [stroke-width:3]")),
			part("zone",
				p("M0 122 L55 124 M265 136 L560 150", "fill-none "+stroke+" [stroke-dasharray:6_5]")),
			part("sanandreas", h.El("circle", h.Attr("cx", "470"), h.Attr("cy", "60"), h.Attr("r", "16"), h.Class(fill(12)))),
			arrow(150, 100, 90, 98), arrow(170, 162, 230, 164),
			h.El("text", h.Attr("x", "470"), h.Attr("y", "64"), h.Attr("text-anchor", "middle"), h.Class("pointer-events-none fill-muted-foreground font-mono text-[10px]"), "SA"),
			h.El("text", h.Attr("x", "8"), h.Attr("y", "250"), h.Class("fill-muted-foreground font-mono text-[10px]"), "map view, seen from above"),
		)
	}
}

