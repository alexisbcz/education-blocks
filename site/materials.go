// matIndex is one Miller index: an integer from −3 to 3 you can drag or type.
func matIndex(name string, v int) h.Node {
	return h.Label(h.Class("flex flex-col items-center gap-0.5"),
		h.Input(h.Type("text"), h.Attr("inputmode", "numeric"), h.Data("scrub", name), h.Value(fmt.Sprint(v)),
			h.Data("min", "-3"), h.Data("max", "3"), h.Data("step", "1"), h.Attr("autocomplete", "off"), h.Aria("label", "Index "+name),
			h.Class("h-9 w-full cursor-ew-resize rounded-md border border-input bg-background text-center font-mono text-base tabular-nums shadow-xs outline-none focus:cursor-text focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50 data-[scrubbing]:border-ring")),
		h.Span(h.Class("font-mono text-[11px] text-muted-foreground"), name),
	)
}

