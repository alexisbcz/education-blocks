// Finite groups as Cayley tables: elements are indices 0..n−1, `t[a][b]` is
// the index of a·b. Every group here is built from an exact rule, and the
// table is then the single source for orders, inverses, subgroups and
// conjugacy classes.

export function fromRule(names, op) {
  const n = names.length;
  const t = Array.from({ length: n }, (_, a) => Array.from({ length: n }, (_, b) => op(a, b)));
  const e = names.findIndex((_, i) => t[i].every((v, j) => v === j));
  return { names, t, e, n };
}

export const cyclic = (n) => fromRule(Array.from({ length: n }, (_, i) => String(i)), (a, b) => (a + b) % n);

const sup = (k) => String(k).replace(/\d/g, (d) => "⁰¹²³⁴⁵⁶⁷⁸⁹"[d]);
const rName = (k) => (k === 0 ? "" : k === 1 ? "r" : "r" + sup(k));

// Dₙ: r^k s^f has index k + n·f; (r^a s^e)(r^b s^f) = r^(a + (−1)^e b) s^(e+f).
export function dihedral(n) {
  const names = [];
  for (let f = 0; f < 2; f++) for (let k = 0; k < n; k++) names.push(f ? rName(k) + "s" : k ? rName(k) : "e");
  return fromRule(names, (x, y) => {
    const a = x % n, e = Math.floor(x / n), b = y % n, f = Math.floor(y / n);
    const k = (((a + (e ? -b : b)) % n) + n) % n;
    return k + n * ((e + f) % 2);
  });
}

/** Cycle notation of a permutation p of 0..n−1 (1-based labels). */
export function cycles(p) {
  const seen = new Array(p.length).fill(false);
  const out = [];
  for (let i = 0; i < p.length; i++) {
    if (seen[i]) continue;
    const c = [];
    for (let j = i; !seen[j]; j = p[j]) { seen[j] = true; c.push(j + 1); }
    if (c.length > 1) out.push(c);
  }
  return out;
}
export const cycleString = (p) => { const c = cycles(p); return c.length ? c.map((x) => `(${x.join(" ")})`).join("") : "e"; };

function permutations(n) {
  if (n === 0) return [[]];
  return permutations(n - 1).flatMap((p) => Array.from({ length: n }, (_, i) => [...p.slice(0, i), n - 1, ...p.slice(i)]));
}

// Sₙ with σ·τ = σ ∘ τ (τ first), elements sorted by cycle type then name.
export function symmetric(n) {
  const ps = permutations(n).sort((a, b) => {
    const ka = cycles(a).map((c) => c.length).sort().join(), kb = cycles(b).map((c) => c.length).sort().join();
    return ka === kb ? cycleString(a).localeCompare(cycleString(b)) : ka.length - kb.length || ka.localeCompare(kb);
  });
  const key = (p) => p.join(",");
  const index = new Map(ps.map((p, i) => [key(p), i]));
  return { ...fromRule(ps.map(cycleString), (a, b) => index.get(key(ps[a].map((_, x) => ps[a][ps[b][x]])))), perms: ps };
}

// Q₈ = {±1, ±i, ±j, ±k}: unit products from i² = j² = k² = ijk = −1.
export function quaternion() {
  const units = ["1", "i", "j", "k"];
  const table = { "11": [1, "1"], "1i": [1, "i"], "1j": [1, "j"], "1k": [1, "k"], i1: [1, "i"], ii: [-1, "1"], ij: [1, "k"], ik: [-1, "j"], j1: [1, "j"], ji: [-1, "k"], jj: [-1, "1"], jk: [1, "i"], k1: [1, "k"], ki: [1, "j"], kj: [-1, "i"], kk: [-1, "1"] };
  const elems = [];
  for (const s of [1, -1]) for (const u of units) elems.push([s, u]);
  const names = elems.map(([s, u]) => (s < 0 ? "−" : "") + u);
  return fromRule(names, (a, b) => {
    const [sa, ua] = elems[a], [sb, ub] = elems[b];
    const [s, u] = table[ua + ub];
    return elems.findIndex(([x, y]) => x === sa * sb * s && y === u);
  });
}

export function inverse(G, a) { return G.t[a].indexOf(G.e); }
export function power(G, a) {
  const out = [G.e];
  for (let x = a; x !== G.e; x = G.t[x][a]) out.push(x);
  return out;
}
export const order = (G, a) => power(G, a).length;
export const isAbelian = (G) => G.t.every((row, a) => row.every((v, b) => v === G.t[b][a]));
export const isCyclic = (G) => G.names.some((_, a) => order(G, a) === G.n);
export function conjugacyClass(G, x) {
  const s = new Set();
  for (let g = 0; g < G.n; g++) s.add(G.t[G.t[g][x]][inverse(G, g)]);
  return [...s].sort((a, b) => a - b);
}
export function classes(G) {
  const seen = new Set(), out = [];
  for (let x = 0; x < G.n; x++) if (!seen.has(x)) { const c = conjugacyClass(G, x); c.forEach((y) => seen.add(y)); out.push(c); }
  return out;
}
export const centre = (G) => G.names.map((_, a) => a).filter((a) => G.t[a].every((v, b) => v === G.t[b][a]));

/** The subgroup generated by a list of elements (closure under products). */
export function closure(G, gens) {
  const set = new Set([G.e, ...gens]);
  let grew = true;
  while (grew) {
    grew = false;
    for (const a of [...set]) for (const b of [...set]) { const c = G.t[a][b]; if (!set.has(c)) { set.add(c); grew = true; } }
  }
  return [...set].sort((a, b) => a - b);
}

/** Every subgroup generated by at most two elements (all subgroups for the groups used here), smallest first. */
export function subgroups(G) {
  const found = new Map();
  const add = (gens) => { const H = closure(G, gens); const k = H.join(","); if (!found.has(k)) found.set(k, { H, gens }); };
  add([]);
  for (let a = 0; a < G.n; a++) add([a]);
  for (let a = 0; a < G.n; a++) for (let b = a + 1; b < G.n; b++) add([a, b]);
  return [...found.values()].sort((x, y) => x.H.length - y.H.length || x.H.join().localeCompare(y.H.join()));
}

export const gcd = (a, b) => (b ? gcd(b, a % b) : Math.abs(a));
export const lcm = (a, b) => (a / gcd(a, b)) * b;
