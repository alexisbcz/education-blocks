const outs = (root) => Object.fromEntries([...root.querySelectorAll("[data-out]")].map((n) => [n.dataset.out, n]));
const reduced = () => matchMedia("(prefers-reduced-motion: reduce)").matches;
const isDark = () => document.documentElement.classList.contains("dark");
const onTheme = (fn) => new MutationObserver(fn).observe(document.documentElement, { attributes: true, attributeFilter: ["class"] });
const node = (tag, cls, txt) => { const e = document.createElement(tag); if (cls) e.className = cls; if (txt !== undefined) e.textContent = txt; return e; };
// One hue per element, readable in both themes.
const tint = (i, n) => `oklch(${isDark() ? 0.34 : 0.9} ${isDark() ? 0.07 : 0.06} ${(360 * i) / n})`;
const setList = (G, idx) => `{${idx.map((i) => G.names[i]).join(", ")}}`;

function buildGroup(kind, n) {
  return kind === "z" ? cyclic(n) : kind === "d" ? dihedral(n) : kind === "s3" ? symmetric(3) : kind === "s4" ? symmetric(4) : kind === "q8" ? quaternion() : kind === "z12" ? cyclic(12) : kind === "d4" ? dihedral(4) : symmetric(3);
}

// A Cayley table as an HTML table; `mark(a, b)` may return a class for a cell.
function cayleyTable(G, { onPick, picked, highlight } = {}) {
  const tbl = node("table", "border-separate border-spacing-0.5 font-mono text-[11px] tabular-nums");
  const head = node("tr");
  head.append(node("th", "sticky top-0 left-0 z-20 bg-code px-1 text-muted-foreground", "·"));
  G.names.forEach((nm, b) => {
    const th = node("th", "sticky top-0 z-10 bg-code p-0");
    if (onPick) {
      const btn = node("button", "min-w-7 rounded px-1 py-0.5 outline-none transition-colors duration-100 hover:bg-accent focus-visible:ring-2 focus-visible:ring-ring/50" + (picked === b ? " bg-brand/15 text-brand" : ""), nm);
      btn.type = "button";
      btn.addEventListener("click", () => onPick(b));
      th.append(btn);
    } else th.textContent = nm;
    head.append(th);
  });
  tbl.append(head);
  G.t.forEach((row, a) => {
    const tr = node("tr");
    const th = node("th", "sticky left-0 z-10 bg-code px-1 text-left font-normal", G.names[a]);
    if (picked === a) th.className += " text-brand";
    tr.append(th);
    row.forEach((v, b) => {
      const td = node("td", "min-w-7 rounded px-1 py-0.5 text-center", G.names[v]);
      td.style.background = tint(v, G.n);
      if (highlight && !(highlight.has(a) && highlight.has(b))) td.style.opacity = "0.35";
      if (picked !== undefined && v === G.e && (a === picked || b === picked)) td.style.boxShadow = "inset 0 0 0 1.5px var(--brand)";
      tr.append(td);
    });
    tbl.append(tr);
  });
  return tbl;
}

