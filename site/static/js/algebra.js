function parsePerm(str) {
  const v = str.trim().split(/[\s,]+/).filter(Boolean).map(Number);
  const n = v.length;
  if (n < 2 || n > 9) return null;
  const seen = new Set(v);
  if (seen.size !== n || v.some((x) => !Number.isInteger(x) || x < 1 || x > n)) return null;
  return v.map((x) => x - 1);
}
const compose = (s, t) => t.map((_, x) => s[t[x]]); // σ∘τ: τ first
const permOrder = (p) => cycles(p).reduce((a, c) => lcm(a, c.length), 1);
const sign = (p) => (cycles(p).filter((c) => c.length % 2 === 0).length % 2 ? -1 : 1);
const oneLine = (p) => p.map((x) => x + 1).join(" ");

