function gf4() {
  const names = ["0", "1", "a", "a+1"];
  const mul = (x, y) => { let r = 0; for (let i = 0; i < 2; i++) if (y & (1 << i)) r ^= x << i; if (r & 4) r ^= 0b111; return r; }; // mod x² + x + 1
  return { names, n: 4, add: (x, y) => x ^ y, mul };
}

