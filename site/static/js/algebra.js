for (const root of document.querySelectorAll("[data-alg-cosets]")) {
  const host = root.querySelector("[data-cosets]"), quot = root.querySelector("[data-quotient]"), list = root.querySelector("[data-subgroups]");
  const o = outs(root);
  let kind = "z12", G, subs, sel = 1;
  root.addEventListener("seg-change", (e) => { kind = e.detail.value; load(); });
  onTheme(() => draw());

  function load() {
    G = buildGroup(kind);
    subs = subgroups(G);
    sel = Math.min(1, subs.length - 1);
    list.replaceChildren(...subs.map((sg, i) => {
      const b = node("button", "rounded-full border px-2.5 py-1 font-mono text-[11px] text-muted-foreground outline-none transition-colors duration-150 hover:text-foreground focus-visible:ring-[3px] focus-visible:ring-ring/50 aria-selected:border-brand aria-selected:bg-brand/10 aria-selected:text-brand",
        sg.H.length === 1 ? "{e}" : sg.H.length === G.n ? "G" : `⟨${sg.gens.map((g) => G.names[g]).join(", ")}⟩ · ${sg.H.length}`);
      b.type = "button";
      b.setAttribute("role", "option");
      b.addEventListener("click", () => { sel = i; draw(); });
      return b;
    }));
    draw();
  }

  function draw() {
    const H = subs[sel].H;
    [...list.children].forEach((b, i) => b.setAttribute("aria-selected", String(i === sel)));
    const left = [], right = [], owner = new Array(G.n).fill(-1);
    for (let g = 0; g < G.n; g++) {
      if (owner[g] >= 0) continue;
      const c = H.map((h) => G.t[g][h]).sort((a, b) => a - b);
      c.forEach((x) => (owner[x] = left.length));
      left.push({ rep: g, c });
    }
    for (const { rep } of left) right.push(H.map((h) => G.t[h][rep]).sort((a, b) => a - b).join());
    const normal = left.every(({ c, rep }) => c.join() === H.map((h) => G.t[h][rep]).sort((a, b) => a - b).join());
    host.replaceChildren(...left.map(({ rep, c }, i) => {
      const box = node("div", "flex flex-col gap-1 rounded-lg border p-2");
      box.style.background = tint(i, left.length);
      box.append(node("span", "font-mono text-[10px] text-muted-foreground", `${G.names[rep]}H`), node("span", "font-mono text-xs", c.map((x) => G.names[x]).join("  ")));
      return box;
    }));
    o.lagrange.textContent = `${G.n} = ${H.length} · ${left.length}`;
    o.normal.textContent = normal ? "yes: gH = Hg for every g" : "no: some left coset differs from the right coset";
    if (!normal) { quot.replaceChildren(node("p", "text-xs text-muted-foreground", "Not normal, so the cosets don't form a group.")); o.quot.textContent = "—"; return; }
    // The quotient group: multiply cosets by their representatives.
    const Q = { names: left.map(({ rep }) => `${G.names[rep]}H`), n: left.length };
    Q.t = left.map((A) => left.map((B) => owner[G.t[A.rep][B.rep]]));
    Q.e = owner[G.e];
    quot.replaceChildren(node("p", "mb-1 font-mono text-[11px] text-muted-foreground", "G/H, multiplied by representatives"), cayleyTable(Q));
    o.quot.textContent = `order ${Q.n}${Q.n > 1 && isCyclic(Q) ? ", cyclic" : ""}`;
  }
  load();
}

// ============================================================ Burnside

const PALETTE = ["var(--vec-u)", "var(--brand)", "var(--vec-out)", "var(--ion-cl)"];

for (const root of document.querySelectorAll("[data-alg-burnside]")) {
  const host = root.querySelector("[data-table]"), gallery = root.querySelector("[data-gallery]");
  const o = outs(root);
  let sym = "cyclic";
  const s = scrubAll(root, () => draw());
  root.addEventListener("seg-change", (e) => { sym = e.detail.value; draw(); });

  function draw() {
    const n = Math.round(s.n.get()), k = Math.round(s.k.get());
    const rows = [];
    for (let j = 0; j < n; j++) rows.push({ name: j ? `turn by ${j}` : "identity", cyc: gcd(j, n) || n });
    if (sym === "dihedral") {
      if (n % 2) for (let j = 0; j < n; j++) rows.push({ name: `flip through bead ${j + 1}`, cyc: (n + 1) / 2 });
      else {
        for (let j = 0; j < n / 2; j++) rows.push({ name: `flip through beads ${j + 1}, ${j + 1 + n / 2}`, cyc: n / 2 + 1 });
        for (let j = 0; j < n / 2; j++) rows.push({ name: `flip between beads`, cyc: n / 2 });
      }
    }
    const K = BigInt(k);
    let sum = 0n;
    const tbl = node("table", "w-full font-mono text-xs tabular-nums");
    const hr = node("tr", "border-b text-left text-muted-foreground");
    for (const t of ["symmetry", "cycles", "fixed colourings kᶜ"]) hr.append(node("th", "py-1 pr-3 font-normal", t));
    tbl.append(hr);
    for (const r of rows) {
      const fixed = K ** BigInt(r.cyc);
      sum += fixed;
      const tr = node("tr", "border-b last:border-b-0");
      tr.append(node("td", "py-1 pr-3", r.name), node("td", "py-1 pr-3", String(r.cyc)), node("td", "py-1 pr-3", fixed.toLocaleString("en")));
      tbl.append(tr);
    }
    host.replaceChildren(tbl);
    const orbits = sum / BigInt(rows.length);
    o.all.textContent = (K ** BigInt(n)).toLocaleString("en");
    o.g.textContent = String(rows.length);
    o.orbits.textContent = `${sum.toLocaleString("en")} ÷ ${rows.length} = ${orbits.toLocaleString("en")}`;

    // Brute force check (small cases): canonical form = smallest image.
    const total = k ** n;
    gallery.replaceChildren();
    if (total > 300000) { o.brute.textContent = `skipped (${total.toLocaleString("en")} colourings)`; return; }
    const reps = new Set();
    const seq = new Array(n);
    for (let c = 0; c < total; c++) {
      let x = c;
      for (let i = 0; i < n; i++) { seq[i] = x % k; x = Math.floor(x / k); }
      let best = null;
      for (let j = 0; j < n; j++) for (const flip of sym === "dihedral" ? [false, true] : [false]) {
        let str = "";
        for (let i = 0; i < n; i++) str += seq[flip ? (j - i + n) % n : (i + j) % n];
        if (best === null || str < best) best = str;
      }
      reps.add(best);
    }
    o.brute.textContent = `${reps.size.toLocaleString("en")} ${BigInt(reps.size) === orbits ? "✓ matches" : "✗ mismatch"}`;
    [...reps].sort().slice(0, 60).forEach((str) => {
      const ns = "http://www.w3.org/2000/svg";
      const svg = document.createElementNS(ns, "svg");
      svg.setAttribute("viewBox", "-1.3 -1.3 2.6 2.6");
      svg.setAttribute("class", "size-9");
      const ring = document.createElementNS(ns, "circle");
      ring.setAttribute("r", "0.9"); ring.setAttribute("style", "fill:none;stroke:currentColor;stroke-opacity:0.25;stroke-width:0.06");
      svg.append(ring);
      [...str].forEach((ch, i) => {
        const a = -Math.PI / 2 + (2 * Math.PI * i) / n;
        const b = document.createElementNS(ns, "circle");
        b.setAttribute("cx", String(0.9 * Math.cos(a))); b.setAttribute("cy", String(0.9 * Math.sin(a))); b.setAttribute("r", String(Math.min(0.32, 2.4 / n)));
        b.setAttribute("style", `fill:${PALETTE[+ch]};stroke:var(--background);stroke-width:0.05`);
        svg.append(b);
      });
      gallery.append(svg);
    });
    if (reps.size > 60) gallery.append(node("span", "self-center font-mono text-[11px] text-muted-foreground", `+${reps.size - 60} more`));
  }
  draw();
}

