func wxSvg(viewBox, label string, extra ...any) h.Node {
	return h.Svg(append([]any{h.Data("plot", ""), h.ViewBox(viewBox), h.Class("mx-auto block w-full touch-none select-none"), h.Role("img"), h.Aria("label", label)}, extra...)...)
}

func wxNote(s string) h.Node {
	return h.P(h.Class("text-xs leading-relaxed text-muted-foreground"), s)
}

func wxButton(action, label string, icon h.Node) h.Node {
	return button.Button(button.VariantOutline, button.SizeSm, h.Type("button"), h.Data("action", action), icon, label)
}

func wxPlay(label string) h.Node {
	return button.Button(button.VariantOutline, button.SizeSm, h.Type("button"), h.Data("action", "play"),
		hugeicons.PlayIcon(h.Data("icon", "play")), hugeicons.PauseIcon(h.Data("icon", "pause"), h.Hidden()),
		h.Span(h.Data("label", ""), label))
}

// wxWideField is field with a wider input, for values like 1013.2.
func wxWideField(name, lbl, unit string, v, min, max, step float64) h.Node {
	return h.Label(h.Class("flex items-center justify-between gap-3 text-sm"),
		h.Span(h.Class("text-muted-foreground"), lbl),
		h.Span(h.Class("flex items-center gap-1"),
			h.Input(h.Type("text"), h.Attr("inputmode", "decimal"), h.Data("scrub", name), h.Value(fmt.Sprint(v)),
				h.Data("min", fmt.Sprint(min)), h.Data("max", fmt.Sprint(max)), h.Data("step", fmt.Sprint(step)),
				h.Attr("autocomplete", "off"),
				h.Class("h-8 w-20 cursor-ew-resize rounded-md border border-input bg-background text-right font-mono text-sm tabular-nums shadow-xs outline-none transition-[border-color,box-shadow] duration-150 px-2 focus:cursor-text focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50 data-[scrubbing]:border-ring")),
			h.Span(h.Class("w-12 font-mono text-[11px] text-muted-foreground"), unit),
		),
	)
}

func wxLegend(items ...[2]string) h.Node {
	return h.Div(h.Class("flex flex-wrap items-center gap-x-4 gap-y-1 px-1 pt-1 font-mono text-[11px] text-muted-foreground"),
		h.Map(items, func(it [2]string) h.Node { return legendSwatch(it[0], it[1]) }))
}

